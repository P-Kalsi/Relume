#pragma once

// A captured video frame in CPU memory, as produced by every camera source.
// The pixel data is owned by the frame (and recycled through FramePool); the
// layout of each plane, including its stride, is explicit so that camera
// buffers with padded rows can be copied without repacking.

#include <array>
#include <chrono>
#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace relume {

enum class PixelFormat : std::uint8_t {
  kBgra8,  // 1 plane, B G R A bytes per pixel (CoreVideo '32BGRA')
  kRgb8,   // 1 plane, R G B bytes per pixel (file source)
  kNv12,   // 2 planes: Y (1 byte/px), then interleaved Cb Cr at 4:2:0
};

// Quantization range of YCbCr samples. Only meaningful for kNv12.
enum class YuvRange : std::uint8_t {
  kVideo,  // Y 16..235, Cb/Cr 16..240 ('420v')
  kFull,   // Y, Cb, Cr 0..255 ('420f')
};

// YCbCr -> RGB matrix. Only meaningful for kNv12.
enum class YuvMatrix : std::uint8_t { kBt601, kBt709 };

// Where 4:2:0 chroma samples sit relative to luma (H.273 chroma_sample_loc).
// Recorded for diagnostics: the reference conversion uses one chroma sample
// per 2x2 luma block, so its output does not depend on this value.
enum class ChromaLocation : std::uint8_t { kLeft, kCenter, kTopLeft, kTop, kBottomLeft, kBottom, kUnknown };

// Clock domain of VideoFrame::capture_time_ns.
enum class TimestampClock : std::uint8_t {
  kHostTime,   // CoreMedia host time clock (mach_absolute_time based)
  kSynthetic,  // deterministic timestamps generated by FileSource
};

struct PlaneLayout {
  std::size_t offset = 0;        // byte offset of the first row in VideoFrame::data
  std::size_t stride_bytes = 0;  // bytes from one row to the next (>= width * bytes_per_sample)
  std::uint32_t width = 0;       // samples per row
  std::uint32_t height = 0;      // rows
  std::uint32_t bytes_per_sample = 0;
};

struct VideoFrame {
  std::uint64_t frame_id = 0;      // monotonically increasing per source
  std::int64_t capture_time_ns = 0;  // presentation time on `clock`
  TimestampClock clock = TimestampClock::kSynthetic;
  // steady_clock time when the source received the frame. Not comparable to
  // capture_time_ns unless the two clocks are shown to be the same.
  std::chrono::steady_clock::time_point arrival_time{};

  std::uint32_t width = 0;
  std::uint32_t height = 0;
  PixelFormat format = PixelFormat::kBgra8;
  YuvRange range = YuvRange::kVideo;
  YuvMatrix matrix = YuvMatrix::kBt709;
  ChromaLocation chroma_location = ChromaLocation::kUnknown;

  std::array<PlaneLayout, 2> planes{};
  std::uint32_t plane_count = 0;
  std::vector<std::byte> data;
};

std::string_view ToString(PixelFormat format);
std::string_view ToString(YuvRange range);
std::string_view ToString(YuvMatrix matrix);
std::string_view ToString(ChromaLocation location);

// Sets the format, size and plane layout of `frame` and resizes its data.
// Each row's stride is rounded up to a multiple of `row_alignment` bytes
// (1 = tightly packed). Existing capacity in `frame.data` is reused. NV12
// chroma planes are ceil(width/2) x ceil(height/2), as in CoreVideo.
void AllocateFrame(VideoFrame& frame, PixelFormat format, std::uint32_t width, std::uint32_t height,
                   std::size_t row_alignment = 1);

// Checks that the plane layout is consistent with the format and size and
// fits inside `data`. Returns an empty string when valid, otherwise a reason.
// For kNv12 this also requires 4:2:0 subsampling.
std::string ValidateLayout(const VideoFrame& frame);

}  // namespace relume
