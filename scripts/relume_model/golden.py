"""Golden vectors that pin the preprocessing contract.

`python scripts/relume_model/golden.py --write` regenerates
tests/python/golden/preprocess_golden.json. Regenerate only when the contract
is intentionally changed; the tests compare the live implementation against
the committed file.

The C++ tests read preprocess_golden.txt, a plain-text twin written from the
JSON (no JSON library in C++). `--write` writes both; `--write-text` rewrites
only the twin from the committed JSON. A Python test checks they agree.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from relume_model.preprocess import METHODS, preprocess  # noqa: E402
else:
    from .preprocess import METHODS, preprocess

GOLDEN_PATH = Path(__file__).resolve().parents[2] / "tests" / "python" / "golden" / "preprocess_golden.json"
GOLDEN_TEXT_PATH = GOLDEN_PATH.with_suffix(".txt")

# (width, height) of deterministic random images; small odd, portrait, 16:9.
CASES = [(3, 2), (5, 7), (1, 1), (17, 9), (9, 17), (64, 36)]
SAMPLE_POINTS = 24  # tensor positions recorded per case


def _image(w: int, h: int) -> np.ndarray:
    rng = np.random.default_rng(1000 * w + h)
    return rng.integers(0, 256, size=(h, w, 3), dtype=np.uint8)


def build() -> dict:
    cases = []
    for method in METHODS:
        for w, h in CASES:
            image = _image(w, h)
            tensor, transform = preprocess(image, method)
            rng = np.random.default_rng(7 * w + h)
            # Sample inside the image region and anywhere (includes padding).
            ys = np.concatenate([
                rng.integers(transform.pad_y, transform.pad_y + transform.new_h, SAMPLE_POINTS // 2),
                rng.integers(0, 448, SAMPLE_POINTS // 2)])
            xs = np.concatenate([
                rng.integers(transform.pad_x, transform.pad_x + transform.new_w, SAMPLE_POINTS // 2),
                rng.integers(0, 448, SAMPLE_POINTS // 2)])
            samples = [
                {"y": int(y), "x": int(x), "rgb": [float(v) for v in tensor[0, :, y, x]]}
                for y, x in zip(ys, xs)
            ]
            cases.append({
                "method": method,
                "width": w,
                "height": h,
                # Row-major HxWx3 RGB bytes, hex encoded.
                "image_rgb_hex": image.tobytes().hex(),
                "transform": transform.to_dict(),
                "samples": samples,
            })
    return {"description": "Relume preprocessing golden vectors; tensor values are float32 NCHW",
            "cases": cases}


def to_text(golden: dict) -> str:
    """The golden JSON as whitespace-separated lines. Floats use repr(), which
    round-trips the stored values exactly.

        case <method> <width> <height> <new_w> <new_h> <pad_x> <pad_y> <samples>
        rgb <hex bytes, row-major HxWx3>
        s <y> <x> <r> <g> <b>          (one line per sample)
    """
    lines = ["# Generated by scripts/relume_model/golden.py from preprocess_golden.json; do not edit.",
             f"cases {len(golden['cases'])}"]
    for case in golden["cases"]:
        t = case["transform"]
        lines.append(f"case {case['method']} {case['width']} {case['height']} "
                     f"{t['new_w']} {t['new_h']} {t['pad_x']} {t['pad_y']} {len(case['samples'])}")
        lines.append(f"rgb {case['image_rgb_hex']}")
        for s in case["samples"]:
            lines.append(f"s {s['y']} {s['x']} " + " ".join(repr(float(v)) for v in s["rgb"]))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if "--write" in sys.argv:
        GOLDEN_PATH.parent.mkdir(parents=True, exist_ok=True)
        GOLDEN_PATH.write_text(json.dumps(build(), indent=1) + "\n")
        print(f"wrote {GOLDEN_PATH}")
    elif "--write-text" not in sys.argv:
        raise SystemExit("usage: golden.py --write | --write-text")
    GOLDEN_TEXT_PATH.write_text(to_text(json.loads(GOLDEN_PATH.read_text())))
    print(f"wrote {GOLDEN_TEXT_PATH}")
